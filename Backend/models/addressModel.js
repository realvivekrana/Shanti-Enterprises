// ============================================================
// SHANTI ENTERPRISES
// Address Model
// Backend - Customer Saved Addresses
// ============================================================

const mongoose = require("mongoose");

// ============================================================
// ADDRESS SCHEMA
// ============================================================

const addressSchema =
  new mongoose.Schema(
    {
      // ========================================================
      // USER
      // ========================================================

      user: {
        type: mongoose.Schema.Types.ObjectId,
        ref: "User",
        required: true,
        index: true,
      },

      // ========================================================
      // FULL NAME
      // ========================================================

      name: {
        type: String,
        required: true,
        trim: true,
      },

      // ========================================================
      // PHONE
      // ========================================================

      phone: {
        type: String,
        required: true,
        trim: true,
      },

      // ========================================================
      // ADDRESS
      // ========================================================

      address: {
        type: String,
        required: true,
        trim: true,
      },

      // ========================================================
      // CITY
      // ========================================================

      city: {
        type: String,
        required: true,
        trim: true,
      },

      // ========================================================
      // STATE
      // ========================================================

      state: {
        type: String,
        required: true,
        trim: true,
      },

      // ========================================================
      // PINCODE
      // ========================================================

      pincode: {
        type: String,
        required: true,
        trim: true,
        match: [
          /^\d{6}$/,
          "Pincode must contain 6 digits.",
        ],
      },

      // ========================================================
      // DEFAULT ADDRESS
      // ========================================================

      isDefault: {
        type: Boolean,
        default: false,
      },
    },
    {
      timestamps: true,
    }
  );

// ============================================================
// INDEX
// ============================================================

addressSchema.index({
  user: 1,
  isDefault: -1,
});

// ============================================================
// MODEL
// ============================================================

const Address =
  mongoose.model(
    "Address",
    addressSchema
  );

// ============================================================
// EXPORT
// ============================================================

module.exports = Address;